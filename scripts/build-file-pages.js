const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const publicDir = path.join(root, 'public');
const bundleDir = path.join(publicDir, 'Js', 'file-bundles');
const hubPath = path.join(publicDir, 'Js', 'council-hub.js');
const balCalculatorPath = path.join(publicDir, 'Js', 'bal-calculator.js');

const pages = discoverCouncilPages();

fs.mkdirSync(bundleDir, { recursive: true });

const hubCode = transformHub(fs.readFileSync(hubPath, 'utf8'));
const balCalculatorCode = transformHub(fs.readFileSync(balCalculatorPath, 'utf8'));

for (const page of pages) {
  buildPage(page);
}

function discoverCouncilPages() {
  return fs
    .readdirSync(publicDir)
    .filter(file => file.endsWith('.html') && !file.endsWith('-file.html'))
    .filter(file => {
      const html = fs.readFileSync(path.join(publicDir, file), 'utf8');
      return !!findCouncilScript(html);
    })
    .sort();
}

function buildPage(page) {
  const htmlPath = path.join(publicDir, page);
  const councilName = page.replace(/\.html$/i, '');
  const sourceHtml = fs.readFileSync(htmlPath, 'utf8');
  const moduleMatch = findCouncilScript(sourceHtml);
  if (!moduleMatch) {
    throw new Error(`Missing council script in ${htmlPath}`);
  }
  const councilPath = path.join(publicDir, 'Js', 'councils', moduleMatch[1]);
  const outScriptName = `${councilName}-file.js`;
  const outHtmlName = `${councilName}-file.html`;

  if (!fs.existsSync(councilPath)) {
    throw new Error(`Missing council script: ${councilPath}`);
  }

  const councilCode = transformCouncil(fs.readFileSync(councilPath, 'utf8'));
  const script = buildScript(page, balCalculatorCode, hubCode, councilCode);
  fs.writeFileSync(path.join(bundleDir, outScriptName), script);

  const outHtml = transformHtml(sourceHtml, councilName, outScriptName);
  fs.writeFileSync(path.join(publicDir, outHtmlName), outHtml);

  console.log(`Built ${path.join('public', outHtmlName)}`);
}

function transformHub(source) {
  return source
    .replace(/\bexport\s+async\s+function\s+/g, 'async function ')
    .replace(/\bexport\s+function\s+/g, 'function ')
    .replace(/\bexport\s+const\s+/g, 'const ');
}

function transformCouncil(source) {
  let code = source.replace(
    /^\s*import\s*\{[\s\S]*?\}\s*from\s*["']\.\.\/council-hub\.js(?:\?[^"']*)?["'];\s*/m,
    ''
  );

  code = code.replace(
    /^\s*import\s+\*\s+as\s+([A-Za-z_$][\w$]*)\s+from\s+["'](https:\/\/[^"']+)["'];\s*$/gm,
    'const $1 = await import("$2");'
  );

  code = code.replace(
    /^\s*import\s+([A-Za-z_$][\w$]*)\s+from\s+["'](https:\/\/[^"']+)["'];\s*$/gm,
    'const { default: $1 } = await import("$2");'
  );

  code = code.replace(
    /window\.location\.href\s*=\s*([^;\n]*\/api\/stripe\/success[^;]*);/g,
    'if (!window.__LOT_WISE_FILE_MODE__) window.location.href = $1;'
  );

  code = code.replace(
    /await\s+fetch\(([^;\n]*\/api\/finalise-token[^;]*);/g,
    'if (!window.__LOT_WISE_FILE_MODE__) await fetch($1;'
  );

  if (/^\s*import\s/m.test(code) || /^\s*export\s/m.test(code)) {
    const leftover = code
      .split(/\r?\n/)
      .filter(line => /^\s*(import|export)\s/.test(line))
      .join('\n');
    throw new Error(`Unsupported module syntax remains:\n${leftover}`);
  }

  return code;
}

function buildScript(page, balCalculator, hub, council) {
  return [
    '// Generated by scripts/build-file-pages.js. Do not edit directly.',
    '(async function () {',
    '  "use strict";',
    '  window.__LOT_WISE_FILE_MODE__ = true;',
    '  installFileModeApiShim();',
    '',
    indent(balCalculator, 2),
    '',
    indent(hub, 2),
    '',
    indent(council, 2),
    '',
    '})().catch(function (err) {',
    '  console.error(err);',
    '  var panel = document.createElement("div");',
    '  panel.style.cssText = "position:fixed;inset:0;z-index:2147483647;display:grid;place-items:center;background:rgba(10,10,12,.92);color:#fff;font:14px \'Hanken Grotesk\',sans-serif;padding:24px";',
    '  panel.innerHTML = ' + JSON.stringify(errorPanelHtml(page)) + '.replace("__ERROR__", escapeHtml(err && (err.stack || err.message) || String(err)));',
    '  document.body.appendChild(panel);',
    '});',
    '',
    'function escapeHtml(value) {',
    '  return String(value == null ? "" : value)',
    '    .replace(/&/g, "&amp;")',
    '    .replace(/</g, "&lt;")',
    '    .replace(/>/g, "&gt;")',
    '    .replace(/"/g, "&quot;");',
    '}',
    '',
    'function installFileModeApiShim() {',
    '  var nativeFetch = window.fetch ? window.fetch.bind(window) : null;',
    '  if (!nativeFetch) return;',
    '  window.fetch = function (input, init) {',
    '    var raw = typeof input === "string" ? input : input && input.url;',
    '    if (isLocalApiRequest(raw)) {',
    '      return Promise.resolve(fileModeApiResponse(raw));',
    '    }',
    '    return nativeFetch(input, init);',
    '  };',
    '}',
    '',
    'function isLocalApiRequest(raw) {',
    '  raw = String(raw || "");',
    '  if (/^\\/api\\//.test(raw)) return true;',
    '  if (/^file:\\/\\/\\/[^?#]*\\/api\\//i.test(raw)) return true;',
    '  return false;',
    '}',
    '',
    'function fileModeApiResponse(raw) {',
    '  var body;',
    '  if (/\\/api\\/payment-config\\b/.test(raw)) {',
    '    body = { paymentUrl: null, fileMode: true };',
    '  } else if (/\\/api\\/check-token\\b/.test(raw)) {',
    '    body = { ok: true, fileMode: true, expiresAt: new Date(Date.now() + 24 * 60 * 60 * 1000).toISOString() };',
    '  } else {',
    '    body = { ok: true, fileMode: true };',
    '  }',
    '  return new Response(JSON.stringify(body), {',
    '    status: 200,',
    '    headers: { "Content-Type": "application/json; charset=utf-8" }',
    '  });',
    '}',
    ''
  ].join('\n');
}

function errorPanelHtml(page) {
  return [
    '<div style="max-width:680px;background:#17191f;border:1px solid #343844;border-radius:14px;padding:22px;box-shadow:0 24px 64px rgba(0,0,0,.45)">',
    '<h1 style="margin:0 0 10px;font-size:20px">File-mode map failed to start</h1>',
    '<p style="margin:0 0 12px;color:#cfd3dd;line-height:1.45">This no-port page loads the local code from disk and ArcGIS modules from HTTPS. Check internet access and Chrome console details.</p>',
    '<p style="margin:0 0 10px;color:#cfd3dd">Source page: ' + page + '</p>',
    '<pre style="white-space:pre-wrap;margin:0;padding:10px 12px;border-radius:8px;background:#0c0d11;color:#fff;overflow:auto;max-height:280px">__ERROR__</pre>',
    '</div>'
  ].join('');
}

function transformHtml(html, councilName, scriptName) {
  let out = html.replace(
    /\s*<script\s+src=["']\.\/file-protocol-guard\.js["']><\/script>\s*/i,
    '\n'
  );

  out = out.replace(
    /\s*<script\s+src=["'](?:\.\/)?sw-register\.js["']><\/script>\s*/i,
    '\n'
  );

  out = out.replace(
    /\s*<script\s+type=["']module["']\s+src=["']https:\/\/js\.arcgis\.com\/[^"']*\/embeddable-components\/?["']><\/script>\s*/gi,
    '\n'
  );

  out = out.replace(
    /\s*(?:<script\s+type=["']module["']\s+src=["']\.\/Js\/councils\/[^"']+["']><\/script>|<script\s+src=["']\.\/Js\/module-loader\.js(?:\?[^"']*)?["']\s+data-module=["']\.\/Js\/councils\/[^"']+["']><\/script>)\s*/i,
    `\n  <script>window.__LOT_WISE_FILE_PAGE__ = ${JSON.stringify(councilName)};</script>\n  <script src="./Js/file-bundles/${scriptName}"></script>\n`
  );

  out = out.replace(
    /<title>(.*?)<\/title>/i,
    `<title>$1 - File Mode</title>`
  );

  return out;
}

function findCouncilScript(html) {
  return html.match(
    /<script\s+type=["']module["']\s+src=["']\.\/Js\/councils\/([^"'?]+)(?:\?[^"']*)?["']><\/script>/i
  ) || html.match(
    /<script\s+src=["']\.\/Js\/module-loader\.js(?:\?[^"']*)?["']\s+data-module=["']\.\/Js\/councils\/([^"'?]+)(?:\?[^"']*)?["']><\/script>/i
  );
}

function indent(value, spaces) {
  const pad = ' '.repeat(spaces);
  return String(value)
    .replace(/\s+$/g, '')
    .split(/\r?\n/)
    .map(line => (line ? pad + line : ''))
    .join('\n');
}
